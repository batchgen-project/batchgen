class ChatCompletionStreamChoiceDelta(BaseModel):
    """Delta content in streaming response"""
    role: Optional[ChatCompletionRole] = Field(None, description="The role of the author of this message.")
    content: Optional[str] = Field(None, description="The contents of the chunk message.")
    refusal: Optional[str] = Field(None, description="The refusal message generated by the model.")
    tool_calls: Optional[List[ChatCompletionMessageToolCall]] = Field(
        None,
        description="The tool calls generated by the model, such as function calls."
    )
    function_call: Optional[ChatCompletionMessageFunctionCall] = Field(
        None,
        description="Deprecated and replaced by tool_calls.",
        deprecated=True
    )


class ChatCompletionStreamChoice(BaseModel):
    """A chat completion choice in a streaming response"""
    index: int = Field(..., description="The index of the choice in the list of choices.")
    delta: ChatCompletionStreamChoiceDelta = Field(..., description="A chat completion delta generated by streamed model responses.")
    logprobs: Optional[ChatCompletionChoiceLogprobs] = Field(
        None,
        description="Log probability information for the choice."
    )
    finish_reason: Optional[FinishReason] = Field(
        None,
        description="The reason the model stopped generating tokens. This will be 'stop' if the model hit a natural stop point or a provided stop sequence, 'length' if the maximum number of tokens specified in the request was reached, 'content_filter' if content was omitted due to a flag from our content filters, 'tool_calls' if the model called a tool, or 'function_call' (deprecated) if the model called a function."
    )


class ChatCompletionChunk(BaseModel):
    """
    Represents a streamed chunk of a chat completion response returned by model, based on the provided input.
    
    Reference: https://platform.openai.com/docs/api-reference/chat/streaming
    """
    id: str = Field(..., description="A unique identifier for the chat completion. Each chunk has the same ID.")
    object: Literal["chat.completion.chunk"] = Field(
        default="chat.completion.chunk",
        description="The object type, which is always 'chat.completion.chunk'."
    )
    created: int = Field(..., description="The Unix timestamp (in seconds) of when the chat completion was created. Each chunk has the same timestamp.")
    model: str = Field(..., description="The model used for the chat completion.")
    choices: List[ChatCompletionStreamChoice] = Field(..., description="A list of chat completion choices. Can be more than one if n is greater than 1.")
    usage: Optional[CompletionUsage] = Field(
        None,
        description="An optional field that will only be present when you set stream_options: {\"include_usage\": true} in your request. When present, it contains a null value except for the last chunk which contains the token usage statistics for the entire request."
    )
    system_fingerprint: Optional[str] = Field(
        None,
        description="This fingerprint represents the backend configuration that the model runs with. Can be used in conjunction with the seed request parameter to understand when backend changes have been made that might impact determinism."
    )
    service_tier: Optional[str] = Field(
        None,
        description="The service tier used for processing the request."
    )

    class Config:
        use_enum_values = True
        json_schema_extra = {
            "example": {
                "id": "chatcmpl-123",
                "object": "chat.completion.chunk",
                "created": 1694268190,
                "model": "gpt-4o-mini",
                "system_fingerprint": "fp_44709d6fcb",
                "choices": [
                    {
                        "index": 0,
                        "delta": {
                            "role": "assistant",
                            "content": ""
                        },
                        "logprobs": None,
                        "finish_reason": None
                    }
                ]
            }
        }
